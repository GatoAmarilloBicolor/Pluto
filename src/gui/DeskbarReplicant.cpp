std::string format_time_ago(int64_t ts) {
	if (ts <= 0) return "";
	int64_t ago = (int64_t)std::time(nullptr) - ts;
	if (ago < 60)    return "just now";
	if (ago < 3600)  { char b[32]; std::snprintf(b, 32, "%lldm ago", (long long)(ago/60)); return b; }
	if (ago < 86400) { char b[32]; std::snprintf(b, 32, "%lldh ago", (long long)(ago/3600)); return b; }
	char b[32]; std::snprintf(b, 32, "%lldd ago", (long long)(ago/86400)); return b;
}

BBitmap* create_icon_sized(float size) {
	BBitmap* bmp = new BBitmap(BRect(0, 0, size, size), B_RGBA32);
	if (BIconUtils::GetVectorIcon(kPlutoIconData, kPlutoIconDataSize, bmp)
	    == B_OK)
		return bmp;
	delete bmp;
	return nullptr;
}

