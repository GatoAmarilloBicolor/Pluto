DeskbarReplicant::DeskbarReplicant()
	: BView(BRect(0, 0, B_MINI_ICON - 1, B_MINI_ICON - 1), kReplicantName,
	        B_FOLLOW_NONE, B_WILL_DRAW | B_PULSE_NEEDED) {
	fIcon = create_icon_sized(B_MINI_ICON - 1);
}

DeskbarReplicant::DeskbarReplicant(BMessage* archive)
	: BView(archive) {
	fIcon = create_icon_sized(B_MINI_ICON - 1);
}

DeskbarReplicant::~DeskbarReplicant() {
	delete fIcon;
}

BArchivable* DeskbarReplicant::Instantiate(BMessage* archive) {
	if (!validate_instantiation(archive, "pluto::gui::DeskbarReplicant"))
		return nullptr;
	return new DeskbarReplicant(archive);
}

status_t DeskbarReplicant::Archive(BMessage* archive, bool deep) const {
	status_t err = BView::Archive(archive, deep);
	if (err != B_OK) return err;
	archive->AddString("class", "pluto::gui::DeskbarReplicant");
	archive->AddString("add_on", kAppSignature);
	return B_OK;
}

void DeskbarReplicant::AttachedToWindow() {
	BView::AttachedToWindow();
	if (Parent()) {
		SetViewColor(Parent()->ViewColor());
		float h = Parent()->Bounds().Height() - 4;
		if (h < 16) h = 16;
		if (h > 22) h = 22;
		ResizeTo(h, h);
		delete fIcon;
		fIcon = create_icon_sized(h);
	} else {
		SetViewColor(B_TRANSPARENT_COLOR);
	}
	_UpdateToolTip();
}

void DeskbarReplicant::Draw(BRect /*updateRect*/) {
	if (fIcon) {
		SetDrawingMode(B_OP_ALPHA);
		DrawBitmap(fIcon, BPoint(0, 0));
		SetDrawingMode(B_OP_COPY);
	} else {
		SetHighColor(30, 140, 70);
		FillEllipse(BRect(2, 2, 13, 13));
	}
}

void DeskbarReplicant::MouseMoved(BPoint, uint32 transit, const BMessage*) {
	if (transit == B_ENTERED_VIEW)
		_UpdateToolTip();
}

void DeskbarReplicant::MouseDown(BPoint where) {
	// Distinguish left vs right click.
	int32 buttons = 0;
	if (Window() && Window()->CurrentMessage())
		Window()->CurrentMessage()->FindInt32("buttons", &buttons);

	if (buttons & B_SECONDARY_MOUSE_BUTTON) {
		ConvertToScreen(&where);
		_ShowPopup(where);
	} else {
		// Left click: launch or focus Pluto-gui.
		be_roster->Launch(kAppSignature);
	}
}

void DeskbarReplicant::MessageReceived(BMessage* msg) {
	switch (msg->what) {
		case kMsgLaunch:
			be_roster->Launch(kAppSignature);
			break;

		case kMsgNewSession:
			// Launch Pluto-gui fresh (it opens a new conversation).
			be_roster->Launch(kAppSignature);
			break;

		case kMsgQuickPrompt: {
			// Simple alert with a text field for a one-shot prompt.
			BAlert* dlg = new BAlert("Pluto — Quick prompt",
				"Enter a prompt to send to Claude (one-shot):",
				"Cancel", "Send", nullptr,
				B_WIDTH_AS_USUAL, B_INFO_ALERT);
			// BAlert doesn't have a text field, so we use system()
			// with a simple approach: ask via alert, then run CLI.
			int32 rc = dlg->Go();
			if (rc == 1) {
				// Can't get text from BAlert — launch Pluto-gui instead.
				be_roster->Launch(kAppSignature);
			}
			break;
		}

		case kMsgOpenSession:
			// Just bring Pluto-gui to front; it can load from recent sessions menu.
			be_roster->Launch(kAppSignature);
			break;

		default:
			BView::MessageReceived(msg);
	}
}

void DeskbarReplicant::_UpdateToolTip() {
	auto sessions = SessionStore::list();

	BString tip("Pluto — Haiku-native Claude client\n");

	if (sessions.empty()) {
		tip += "No saved sessions.";
	} else {
		int64_t total_in = 0, total_out = 0;
		for (const auto& s : sessions) {
			total_in  += s.tokens_in;
			total_out += s.tokens_out;
		}
		BString stats;
		stats.SetToFormat("%zu session%s  |  %lld in / %lld out tokens",
			sessions.size(),
			sessions.size() == 1 ? "" : "s",
			(long long)total_in, (long long)total_out);
		tip += stats;

		// Show last 3 sessions
		int shown = 0;
		for (const auto& s : sessions) {
			if (shown++ >= 3) break;
			BString line;
			std::string title = s.title.empty() ? s.filename : s.title;
			if (title.size() > 30) { title.resize(27); title += "..."; }
			line.SetToFormat("\n  %s  (%s)",
				title.c_str(),
				format_time_ago(s.updated).c_str());
			tip += line;
		}
	}

	SetToolTip(tip.String());
}

void DeskbarReplicant::_ShowPopup(BPoint screenWhere) {
	BPopUpMenu* menu = new BPopUpMenu("pluto-tray-menu", false, false);

	// Header
	auto sessions = SessionStore::list();
	{
		BString header;
		header.SetToFormat("Pluto  (%zu sessions)", sessions.size());
		BMenuItem* h = new BMenuItem(header.String(), nullptr);
		h->SetEnabled(false);
		menu->AddItem(h);
	}
	menu->AddSeparatorItem();

	// Recent sessions (top 5)
	if (!sessions.empty()) {
		int shown = 0;
		for (const auto& s : sessions) {
			if (shown++ >= 5) break;
			std::string title = s.title.empty() ? s.filename : s.title;
			if (title.size() > 35) { title.resize(32); title += "..."; }
			BString label;
			label.SetToFormat("%s  (%lld tok, %s)",
				title.c_str(),
				(long long)(s.tokens_in + s.tokens_out),
				format_time_ago(s.updated).c_str());
			menu->AddItem(new BMenuItem(label.String(),
				new BMessage(kMsgOpenSession)));
		}
		menu->AddSeparatorItem();
	}

	menu->AddItem(new BMenuItem("New conversation",
		new BMessage(kMsgNewSession)));
	menu->AddItem(new BMenuItem("Open pluto",
		new BMessage(kMsgLaunch)));

	menu->SetTargetForItems(this);
	menu->Go(screenWhere, true, true, true);
	delete menu;
}

bool InstallDeskbarReplicant() {
	BDeskbar deskbar;
	if (!deskbar.IsRunning()) return false;
	deskbar.RemoveItem(kReplicantName);
	DeskbarReplicant* view = new DeskbarReplicant();
	status_t err = deskbar.AddItem(view);
	delete view;
	return err == B_OK;
}

bool RemoveDeskbarReplicant() {
	BDeskbar deskbar;
	return deskbar.RemoveItem(kReplicantName) == B_OK;
}

